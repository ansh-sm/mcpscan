"""Markdown diff report generator for GitHub Pull Request security reviews."""

from typing import List
from mcpscan.diff import DiffReport
from mcpscan.models import Severity


class MarkdownDiffReporter:
    """Renders DiffReport into GitHub PR review comment markdown."""

    SEVERITY_INDICATORS = {
        Severity.CRITICAL: "🔴 CRITICAL",
        Severity.HIGH: "🟠 HIGH",
        Severity.MEDIUM: "🟡 MEDIUM",
        Severity.LOW: "🔵 LOW",
        Severity.INFO: "⚪ INFO",
    }

    def generate(self, diff: DiffReport) -> str:
        """Convert a DiffReport into a structured Markdown document."""
        sections: List[str] = []

        # 1. Header Banner
        delta_str = f"+{diff.score_delta}" if diff.score_delta > 0 else f"{diff.score_delta}"
        if diff.has_regressions:
            status_banner = (
                f"> [!CAUTION]\n"
                f"> **Security Regression Detected:** Score changed by **{delta_str} pts** "
                f"(`{diff.baseline_score}` → `{diff.current_score}`) with **{len(diff.new_findings)} new vulnerability finding(s)**."
            )
        elif diff.is_improved:
            status_banner = (
                f"> [!TIP]\n"
                f"> **Security Posture Improved:** Score increased by **{delta_str} pts** "
                f"(`{diff.baseline_score}` → `{diff.current_score}`) with **{len(diff.resolved_findings)} vulnerability finding(s) resolved**."
            )
        else:
            status_banner = (
                f"> [!NOTE]\n"
                f"> **Security Posture Neutral:** Score unchanged (`{diff.current_score}/100`, Grade `{diff.current_grade.value}`)."
            )

        sections.append(f"# 🛡️ mcpscan Posture Delta Review\n\n{status_banner}\n")

        # 2. Metric Transition Table
        sections.append(
            "## 📊 Posture Comparison\n\n"
            "| Metric | Baseline | Current | Delta |\n"
            "| :--- | :---: | :---: | :---: |\n"
            f"| **Grade** | `{diff.baseline_grade.value}` | `{diff.current_grade.value}` | {'🔴 Degraded' if diff.has_regressions else ('🟢 Improved' if diff.is_improved else '⚪ Neutral')} |\n"
            f"| **Score** | `{diff.baseline_score}` | `{diff.current_score}` | **{delta_str} pts** |\n"
            f"| **New Regressions** | — | `{len(diff.new_findings)}` | {'🔴' if diff.new_findings else '🟢 0'} |\n"
            f"| **Resolved Issues** | — | `{len(diff.resolved_findings)}` | {'🟢' if diff.resolved_findings else '0'} |\n"
            f"| **Unresolved Issues** | — | `{len(diff.unresolved_findings)}` | `{len(diff.unresolved_findings)}` |\n"
        )

        # 3. New Findings (Regressions)
        if diff.new_findings:
            sections.append("## 🚨 New Vulnerabilities (Regressions)\n")
            sections.append("| # | Rule ID | Severity | Component | Finding Summary |\n| :---: | :--- | :---: | :--- | :--- |")
            for i, f in enumerate(diff.new_findings, 1):
                sev = self.SEVERITY_INDICATORS.get(f.severity, f.severity.value)
                sections.append(
                    f"| {i} | `{f.rule_id}` | {sev} | `{f.location.target_name}` | {f.title} |"
                )
            sections.append("\n### Regression Remediation Details\n")
            for i, f in enumerate(diff.new_findings, 1):
                sections.append(
                    f"#### {i}. `{f.rule_id}`: {f.title}\n"
                    f"- **Location:** `{f.location.target_type}` → `{f.location.target_name}` (`{f.location.path or ''}`)\n"
                    f"- **Description:** {f.description}\n"
                    f"- **Remediation:** {f.remediation}\n"
                )
                if f.evidence:
                    sections.append(f"```\nEvidence: {f.evidence}\n```\n")
                sections.append("---\n")

        # 4. Resolved Findings
        if diff.resolved_findings:
            sections.append("## ✅ Resolved Findings (Remediated)\n")
            sections.append("| # | Rule ID | Component | Remediated Issue |\n| :---: | :--- | :--- | :--- |")
            for i, f in enumerate(diff.resolved_findings, 1):
                sections.append(f"| {i} | `{f.rule_id}` | `{f.location.target_name}` | {f.title} |")
            sections.append("\n")

        # 5. Footer
        sections.append(
            "---\n*Generated by [mcpscan](https://github.com/ansh-sm/mcpscan) PR regression gate*\n"
        )

        return "\n".join(sections)

    def save(self, diff: DiffReport, output_path: str) -> None:
        """Write Markdown diff report to disk."""
        content = self.generate(diff)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
